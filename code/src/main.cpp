/*
 * PNP board — spin the TMC2209 "C1" axis continuously on power-up.
 *
 * Target: ESP32-S3-DevKitC (as used on the PNP PCB)
 *
 * C1 driver wiring (traced from PNP.kicad_sch / TMC2209 C1 sheet):
 *   STEP -> GPIO6
 *   DIR  -> GPIO5
 *   EN   -> GPIO48   (active LOW: drive LOW to enable the driver)
 *   UART TX/RX -> GPIO18 / GPIO8   (unused here — standalone STEP/DIR mode)
 *
 * The C1 TMC2209 runs in standalone STEP/DIR mode. Motor current is set by the
 * driver module's onboard VREF potentiometer, and microstep resolution by its
 * MS1/MS2 pins (default 1/8 when left at their power-up state). This firmware
 * only needs to enable the driver, pick a direction, and feed a constant step
 * pulse train.
 *
 * The step train is generated by the ESP32 LEDC (PWM) peripheral, so it's a
 * clean, jitter-free, hardware-driven square wave that keeps running with zero
 * CPU involvement — the motor turns forever as long as the board is powered.
 */

#include <Arduino.h>

// ---- C1 axis pin map ----
static constexpr int PIN_STEP = 6;
static constexpr int PIN_DIR  = 5;
static constexpr int PIN_EN   = 48;  // active LOW

// ---- Motion settings ----
// Step frequency in Hz. With 1/8 microstepping on a 200-step/rev motor
// (1600 microsteps/rev), 2000 Hz ~= 1.25 rev/s (~75 RPM). Tune to taste.
static constexpr uint32_t STEP_HZ   = 2000;
static constexpr uint8_t  DIR_LEVEL = HIGH;  // HIGH or LOW to flip rotation

// LEDC config for the step train (Arduino-ESP32 core 2.x API)
static constexpr uint8_t  STEP_PWM_CHANNEL  = 0;
static constexpr uint8_t  STEP_PWM_RES_BITS = 8;              // 8-bit duty
static constexpr uint32_t STEP_PWM_DUTY_50  = 1 << (STEP_PWM_RES_BITS - 1);

void setup() {
  Serial.begin(115200);

  // Start with the driver DISABLED (EN high) so nothing moves during bring-up.
  pinMode(PIN_EN, OUTPUT);
  digitalWrite(PIN_EN, HIGH);

  // Set direction.
  pinMode(PIN_DIR, OUTPUT);
  digitalWrite(PIN_DIR, DIR_LEVEL);

  // Give the driver a moment to power up before enabling.
  delay(200);

  // Attach LEDC to the STEP pin and start a continuous 50%-duty square wave.
  ledcSetup(STEP_PWM_CHANNEL, STEP_HZ, STEP_PWM_RES_BITS);
  ledcAttachPin(PIN_STEP, STEP_PWM_CHANNEL);
  ledcWrite(STEP_PWM_CHANNEL, STEP_PWM_DUTY_50);

  // Enable the driver — motor starts turning now.
  digitalWrite(PIN_EN, LOW);

  Serial.printf("TMC2209 C1 spinning: STEP=GPIO%d DIR=GPIO%d EN=GPIO%d @ %lu Hz\n",
                PIN_STEP, PIN_DIR, PIN_EN, (unsigned long)STEP_HZ);
}

void loop() {
  // Nothing to do — the LEDC hardware keeps the step train running on its own.
  delay(1000);
}
